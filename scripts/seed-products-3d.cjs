async function seed() {
  const uri = process.env.MONGO_URI || 'mongodb+srv://bossUser:aZw9Y5zl1jtHutu1@cluster0.z51z0nl.mongodb.net/turrim_db?retryWrites=true&w=majority';
  console.log('Connecting to MongoDB...');
  await mongoose.connect(uri);

  const col = mongoose.connection.collection('product3ds');

  console.log('Upserting 26 alphabet items...');
  for (const item of alphabet) {
    await col.updateOne(
      { letter: item.letter },
      {
        $set: {
          ...item,
          updatedAt: new Date(),
        },
        $setOnInsert: {
          createdAt: new Date(),
        },
      },
      { upsert: true }
    );
  }

  // Remove old unassigned/test documents without a letter
  const deleteResult = await col.deleteMany({ letter: { $exists: false } });
  if (deleteResult.deletedCount > 0) {
    console.log(`Cleaned up ${deleteResult.deletedCount} legacy documents without letter.`);
  }

  const total = await col.countDocuments({ letter: { $exists: true } });
  console.log(`Seed completed successfully! Total alphabet 3D products: ${total}`);
  await mongoose.disconnect();
}

seed().catch((err) => {
  console.error('Seed error:', err);
  process.exit(1);
});
